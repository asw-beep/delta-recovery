"""
Synthetic payment-failure dataset with full potential outcomes.

Why this exists
---------------
The product's claim is about *incremental* recovery: money that would not have
come back on its own. Measuring that honestly needs the counterfactual — what
would have happened had we not contacted this customer — and no real dataset
contains it. So we generate one, and document the generating process so the
result is auditable rather than magical.

Two design choices carry the whole evaluation:

1. Every risk item gets its FULL potential-outcome vector: y(do_nothing) and
   y(contact). The harness can then score any policy on the same items, and an
   oracle policy is computable, which bounds our claim from above.

2. The logged action is chosen by a RANDOMISED policy, not a sensible rule.
   Training data generated by a rule inherits that rule's blind spots and makes
   the evaluation circular.

The structure below is deliberately adversarial to our own approach: transient
failures — the ones a naive system rushes to chase — are given high
self-recovery, so contacting them earns almost nothing. If the agent cannot
learn to leave them alone, it deserves to lose to the baselines.

    python eval/generate.py
"""

from __future__ import annotations

import json
import math
import os
import random
from dataclasses import dataclass, asdict

import numpy as np
import pandas as pd

SEED = 20260823
DAYS = 90
N_CUSTOMERS = 3000
N_ORDERS = 45000
N_INVOICES = 4000

TRAIN_END, VAL_END = 60, 75  # test is 76..90

OUT_DIR = os.path.dirname(os.path.abspath(__file__))

rng = np.random.default_rng(SEED)
random.seed(SEED)


# ─── World ──────────────────────────────────────────────────────────────────

MERCHANTS = [
    # name,        vertical,     log-mean amount (paise), sigma, method mix
    ("edtech", "education", math.log(450_000), 0.65),
    ("d2c", "retail", math.log(180_000), 0.80),
    ("saas", "b2b", math.log(1_200_000), 0.55),
]

METHODS = ["card", "netbanking", "upi", "wallet"]
METHOD_P = {
    "education": [0.45, 0.20, 0.30, 0.05],
    "retail": [0.35, 0.10, 0.50, 0.05],
    "b2b": [0.55, 0.35, 0.08, 0.02],
}

BANKS = ["HDFC", "ICICI", "SBIN", "AXIS", "KKBK", "PUNB"]

# Failure reasons, conditioned on the underlying cause. These are the exact
# enum values Razorpay documents (see DECISIONS.md §3) — not invented ones.
REASON_BY_CAUSE = {
    "infra": ["gateway_technical_error", "bank_technical_error", "payment_timed_out"],
    "customer": ["payment_cancelled", "authentication_failed", "incorrect_cvv", "insufficient_funds"],
    "instrument": [
        "card_expired",
        "debit_instrument_blocked",
        "debit_instrument_inactive",
        "card_not_enrolled",
        "card_disabled_for_online_payments",
    ],
    "risk": ["payment_risk_check_failed"],
    "opaque": ["card_declined", "payment_failed", "transaction_limit_exceeded"],
}

TAXONOMY = {
    "gateway_technical_error": "TRANSIENT",
    "bank_technical_error": "TRANSIENT",
    "payment_timed_out": "TRANSIENT",
    "payment_cancelled": "CUSTOMER_FIXABLE",
    "authentication_failed": "CUSTOMER_FIXABLE",
    "incorrect_cvv": "CUSTOMER_FIXABLE",
    "insufficient_funds": "CUSTOMER_FIXABLE",
    "card_expired": "INSTRUMENT_DEAD",
    "debit_instrument_blocked": "INSTRUMENT_DEAD",
    "debit_instrument_inactive": "INSTRUMENT_DEAD",
    "card_not_enrolled": "INSTRUMENT_DEAD",
    "card_disabled_for_online_payments": "INSTRUMENT_DEAD",
    "payment_risk_check_failed": "DO_NOT_TOUCH",
    "card_declined": "OPAQUE",
    "payment_failed": "OPAQUE",
    "transaction_limit_exceeded": "OPAQUE",
}

ERROR_STEP = {
    "TRANSIENT": "payment_authorization",
    "CUSTOMER_FIXABLE": "payment_authentication",
    "INSTRUMENT_DEAD": "payment_authorization",
    "DO_NOT_TOUCH": "payment_authorization",
    "OPAQUE": "payment_authorization",
}

ERROR_SOURCE = {
    "TRANSIENT": "gateway",
    "CUSTOMER_FIXABLE": "customer",
    "INSTRUMENT_DEAD": "issuer",
    "DO_NOT_TOUCH": "issuer",
    "OPAQUE": "bank",
}

CAUSE_P = [0.26, 0.30, 0.18, 0.04, 0.22]
CAUSES = ["infra", "customer", "instrument", "risk", "opaque"]


# ─── Customers ──────────────────────────────────────────────────────────────

@dataclass
class Customer:
    id: int
    merchant: str
    reliability: float   # latent propensity to complete a payment
    payday_dom: int      # day of month money arrives
    tenure_days: int
    ltv_band: int        # 0 low, 1 mid, 2 high


def make_customers() -> list[Customer]:
    out = []
    for i in range(N_CUSTOMERS):
        m = MERCHANTS[rng.integers(0, len(MERCHANTS))][1]
        out.append(
            Customer(
                id=i,
                merchant=m,
                reliability=float(rng.beta(5, 2)),
                payday_dom=int(rng.choice([1, 7, 25])),
                tenure_days=int(rng.integers(1, 900)),
                ltv_band=int(rng.choice([0, 1, 2], p=[0.5, 0.35, 0.15])),
            )
        )
    return out


# ─── Downtime windows ───────────────────────────────────────────────────────

def make_downtimes() -> list[tuple[str, str, float, float]]:
    """(method, bank, start_hour, end_hour) over the whole horizon."""
    windows = []
    total_hours = DAYS * 24
    n = rng.poisson(DAYS * 0.45)  # a few outages a week
    for _ in range(n):
        start = float(rng.uniform(0, total_hours))
        dur = float(rng.uniform(0.3, 3.0))
        windows.append(
            (str(rng.choice(METHODS)), str(rng.choice(BANKS)), start, start + dur)
        )
    return windows


def in_downtime(windows, method, bank, abs_hour) -> bool:
    for m, b, s, e in windows:
        if m == method and b == bank and s <= abs_hour <= e:
            return True
    return False


# ─── The causal core ────────────────────────────────────────────────────────

def p_self_recovery(cls, cust, amount, prior_fails, days_to_payday, downtime) -> float:
    """
    P(customer pays anyway, with no intervention).

    This is the number naive systems ignore, and it is deliberately HIGH for
    transient failures — the population most likely to be chased pointlessly.
    """
    base = {
        "TRANSIENT": 0.55,
        "CUSTOMER_FIXABLE": 0.28,
        "INSTRUMENT_DEAD": 0.06,
        "DO_NOT_TOUCH": 0.03,
        "OPAQUE": 0.22,
    }[cls]

    z = math.log(base / (1 - base))
    z += 1.1 * (cust.reliability - 0.7)          # reliable people self-serve
    z += 0.30 * min(prior_fails, 4) * -1          # repeated failure predicts churn
    z += 0.22 * math.log(max(amount, 1) / 500_000)  # people chase big purchases
    if downtime:
        z -= 0.75                                  # their next attempt fails too
    if cls == "CUSTOMER_FIXABLE" and days_to_payday <= 2:
        z += 0.55                                  # money just landed
    return float(1 / (1 + math.exp(-z)))


def uplift(cls, cust, amount, prior_contacts, days_to_payday, downtime) -> float:
    """
    Incremental effect of contacting: P(pay | contact) − P(pay | do nothing).

    Never large for transient failures, near zero for dead instruments, and it
    decays hard with contact fatigue. This is the structure the model must find.
    """
    base = {
        "TRANSIENT": 0.05,        # they were going to pay anyway
        "CUSTOMER_FIXABLE": 0.26,  # a reminder genuinely helps
        "INSTRUMENT_DEAD": 0.04,   # same instrument still cannot work
        "DO_NOT_TOUCH": 0.00,      # never contacted; policy forbids it
        "OPAQUE": 0.12,
    }[cls]

    u = base
    u *= math.exp(-0.85 * prior_contacts)          # fatigue
    if downtime:
        u *= 0.35                                   # link into an outage is wasted
    if cls == "CUSTOMER_FIXABLE":
        u *= 1.0 + 0.6 * math.exp(-0.5 * days_to_payday)  # timing is the lever
    u *= 0.85 + 0.30 * cust.reliability
    return float(max(0.0, min(u, 0.75)))


def _sig(z: float) -> float:
    return 1 / (1 + math.exp(-z))


def _row(idx, cust, vertical, day, hour, amount, risk_class, p0, u,
         prior_contacts, succ, fails, *, method, bank, downtime,
         days_to_payday, hours_since_event, error_reason, taxonomy_class,
         error_source, error_step) -> dict:
    """
    One risk item with both potential outcomes.

    The two arms share a single uniform draw, so the same "luck" applies to
    both. That is what makes the pair a genuine counterfactual rather than two
    unrelated coin flips, and it is why an oracle policy is computable at all.
    """
    p1 = min(0.98, p0 + u)
    luck = float(rng.random())
    y0 = int(luck < p0)
    y1 = int(luck < p1)
    logged = int(rng.random() < 0.5)  # randomised: unconfounded training data

    return dict(
        risk_id=f"R{idx:06d}",
        risk_class=risk_class,
        customer_id=cust.id,
        merchant=vertical,
        day=day,
        hour=hour,
        weekday=day % 7,
        amount_paise=amount,
        method=method,
        bank=bank,
        error_reason=error_reason,
        taxonomy_class=taxonomy_class,
        error_source=error_source,
        error_step=error_step,
        downtime_active=int(downtime),
        days_to_payday=days_to_payday,
        hours_since_event=round(hours_since_event, 2),
        cust_reliability_hidden=round(cust.reliability, 4),
        cust_success_count=succ,
        cust_failure_count=fails,
        cust_tenure_days=cust.tenure_days,
        ltv_band=cust.ltv_band,
        prior_contacts_7d=prior_contacts,
        # Ground truth. Available to the ORACLE and to nobody else.
        p_do_nothing=round(p0, 5),
        p_contact=round(p1, 5),
        true_uplift=round(p1 - p0, 5),
        y_do_nothing=y0,
        y_contact=y1,
        logged_action=logged,
        y_observed=y1 if logged else y0,
    )


# ─── Abandoned checkout ─────────────────────────────────────────────────────
# No error_reason exists here — Razorpay has no abandonment event, so the signal
# is purely behavioural: how long they have been gone, and who they are.

def p_self_recovery_abandoned(cust, amount, hours_since, prior_fails) -> float:
    z = math.log(0.34 / 0.66)
    z += 1.0 * (cust.reliability - 0.7)
    z -= 0.055 * hours_since                      # the trail goes cold
    z += 0.18 * math.log(max(amount, 1) / 300_000)
    z -= 0.25 * min(prior_fails, 4)
    return _sig(z)


def uplift_abandoned(cust, amount, hours_since, prior_contacts) -> float:
    u = 0.24
    u *= math.exp(-0.030 * max(0.0, hours_since - 4))  # peaks early, then fades
    u *= math.exp(-0.85 * prior_contacts)
    u *= 0.85 + 0.30 * cust.reliability
    return float(max(0.0, min(u, 0.75)))


# ─── Overdue receivables ────────────────────────────────────────────────────
# B2B invoices mostly get paid eventually. That makes self-recovery HIGH and
# uplift SMALL, while amounts are the largest in the portfolio — which is exactly
# the trap for anyone who prioritises by ticket size.

def p_self_recovery_receivable(cust, days_overdue) -> float:
    z = math.log(0.70 / 0.30)
    z += 0.8 * (cust.reliability - 0.7)
    z -= 0.020 * days_overdue
    return _sig(z)


def uplift_receivable(cust, days_overdue, prior_contacts) -> float:
    u = 0.09
    u *= 1 + 0.35 * math.tanh(days_overdue / 20.0)  # chasing helps more when late
    u *= math.exp(-0.70 * prior_contacts)
    u *= 0.85 + 0.30 * cust.reliability
    return float(max(0.0, min(u, 0.60)))


# ─── Generation ─────────────────────────────────────────────────────────────

def main() -> None:
    customers = make_customers()
    downtimes = make_downtimes()

    rows = []
    fail_counts = {c.id: 0 for c in customers}
    success_counts = {c.id: 0 for c in customers}
    contacts_7d: dict[int, list[float]] = {c.id: [] for c in customers}

    for _ in range(N_ORDERS):
        cust = customers[int(rng.integers(0, N_CUSTOMERS))]
        merch = next(m for m in MERCHANTS if m[1] == cust.merchant)
        _, vertical, logmu, sigma = merch

        day = int(rng.integers(1, DAYS + 1))
        hour = int(rng.choice(range(24), p=_hour_weights()))
        abs_hour = (day - 1) * 24 + hour

        amount = int(min(rng.lognormal(logmu, sigma), 5_000_000))
        method = str(rng.choice(METHODS, p=METHOD_P[vertical]))
        bank = str(rng.choice(BANKS))
        downtime = in_downtime(downtimes, method, bank, abs_hour)

        # Does this payment fail?
        z = -1.85
        z += -1.4 * (cust.reliability - 0.7)
        z += 0.18 * math.log(max(amount, 1) / 500_000)
        if downtime:
            z += 2.2
        if method == "netbanking":
            z += 0.25
        if hour in (1, 2, 3, 4):
            z += 0.20
        failed = rng.random() < 1 / (1 + math.exp(-z))

        dom = ((day - 1) % 30) + 1
        days_to_payday = (cust.payday_dom - dom) % 30
        recent_contacts = len([t for t in contacts_7d[cust.id] if abs_hour - t <= 168])

        # ── Abandonment: the customer never even attempted payment ──────────
        # Independent of failure — this is the order that sits there unpaid.
        if not failed and rng.random() < 0.10:
            hours_since = float(rng.gamma(2.0, 6.0))  # long right tail
            p0 = p_self_recovery_abandoned(cust, amount, hours_since, fail_counts[cust.id])
            u = uplift_abandoned(cust, amount, hours_since, recent_contacts)
            rows.append(
                _row(
                    len(rows), cust, vertical, day, hour, amount, "abandoned_checkout",
                    p0, u, recent_contacts, success_counts[cust.id], fail_counts[cust.id],
                    method=method, bank=bank, downtime=downtime,
                    days_to_payday=days_to_payday, hours_since_event=hours_since,
                    error_reason="", taxonomy_class="ABANDONED",
                    error_source="", error_step="",
                )
            )
            if rows[-1]["logged_action"]:
                contacts_7d[cust.id].append(abs_hour)
            continue

        if not failed:
            success_counts[cust.id] += 1
            continue

        cause = str(rng.choice(CAUSES, p=CAUSE_P))
        # Instrument failures are a card phenomenon; keep the world coherent.
        if cause == "instrument" and method != "card":
            cause = "opaque"
        reason = str(rng.choice(REASON_BY_CAUSE[cause]))
        cls = TAXONOMY[reason]
        prior_fails = fail_counts[cust.id]

        p0 = p_self_recovery(cls, cust, amount, prior_fails, days_to_payday, downtime)
        u = uplift(cls, cust, amount, recent_contacts, days_to_payday, downtime)

        rows.append(
            _row(
                len(rows), cust, vertical, day, hour, amount, "failed_payment",
                p0, u, recent_contacts, success_counts[cust.id], prior_fails,
                method=method, bank=bank, downtime=downtime,
                days_to_payday=days_to_payday,
                hours_since_event=float(rng.gamma(1.5, 3.0)),
                error_reason=reason, taxonomy_class=cls,
                error_source=ERROR_SOURCE[cls], error_step=ERROR_STEP[cls],
            )
        )
        if rows[-1]["logged_action"]:
            contacts_7d[cust.id].append(abs_hour)
        fail_counts[cust.id] += 1

    # ── Overdue receivables ─────────────────────────────────────────────────
    # Generated separately: invoices are a B2B instrument with their own cadence,
    # amounts an order of magnitude larger, and a very different economic shape.
    b2b = [c for c in customers if c.merchant == "b2b"]
    for _ in range(N_INVOICES):
        cust = b2b[int(rng.integers(0, len(b2b)))]
        day = int(rng.integers(1, DAYS + 1))
        hour = int(rng.integers(9, 19))  # business hours
        abs_hour = (day - 1) * 24 + hour
        amount = int(min(rng.lognormal(math.log(2_500_000), 0.75), 20_000_000))

        if rng.random() > 0.32:  # most invoices are paid on time and never at risk
            continue

        days_overdue = float(rng.gamma(2.0, 9.0))
        recent_contacts = len([t for t in contacts_7d[cust.id] if abs_hour - t <= 168])

        p0 = p_self_recovery_receivable(cust, days_overdue)
        u = uplift_receivable(cust, days_overdue, recent_contacts)

        rows.append(
            _row(
                len(rows), cust, "b2b", day, hour, amount, "overdue_receivable",
                p0, u, recent_contacts, success_counts[cust.id], fail_counts[cust.id],
                method="", bank="", downtime=False, days_to_payday=0,
                hours_since_event=days_overdue * 24,
                error_reason="", taxonomy_class="RECEIVABLE",
                error_source="", error_step="",
            )
        )
        if rows[-1]["logged_action"]:
            contacts_7d[cust.id].append(abs_hour)

    df = pd.DataFrame(rows)

    # Splits are grouped by time AND by customer: a customer never straddles the
    # train/test boundary, so neither temporal nor per-customer traits leak.
    test_customers = set(df.loc[df.day > VAL_END, "customer_id"].unique())
    df["split"] = np.where(
        df.day <= TRAIN_END,
        "train",
        np.where(df.day <= VAL_END, "val", "test"),
    )
    leak = (df.split.isin(["train", "val"])) & (df.customer_id.isin(test_customers))
    df = df[~leak].copy()

    path = os.path.join(OUT_DIR, "risk_items.csv")
    df.to_csv(path, index=False)

    manifest = dict(
        seed=SEED,
        days=DAYS,
        customers=N_CUSTOMERS,
        orders_attempted=N_ORDERS,
        risk_items=len(df),
        splits={k: int(v) for k, v in df.split.value_counts().items()},
        dropped_for_customer_leakage=int(leak.sum()),
        logging_policy="bernoulli(0.5) — randomised, unconfounded",
        mean_p_do_nothing=round(float(df.p_do_nothing.mean()), 4),
        mean_true_uplift=round(float(df.true_uplift.mean()), 4),
        class_mix={k: int(v) for k, v in df.risk_class.value_counts().items()},
        taxonomy_mix={k: int(v) for k, v in df.taxonomy_class.value_counts().items()},
        mean_amount_by_class={k: int(v) for k, v in df.groupby("risk_class").amount_paise.mean().items()},
        mean_uplift_by_class={k: round(float(v), 4) for k, v in df.groupby("risk_class").true_uplift.mean().items()},
        mean_self_recovery_by_class={k: round(float(v), 4) for k, v in df.groupby("risk_class").p_do_nothing.mean().items()},
    )
    with open(os.path.join(OUT_DIR, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)

    print(json.dumps(manifest, indent=2))
    print(f"\nwrote {len(df)} risk items -> {path}")


def _hour_weights():
    """Indian consumer payment traffic: quiet nights, evening peak."""
    w = np.array([0.6, 0.4, 0.3, 0.3, 0.4, 0.7, 1.0, 1.4, 1.8, 2.0, 2.1, 2.0,
                  1.9, 1.8, 1.8, 1.9, 2.0, 2.2, 2.4, 2.5, 2.2, 1.7, 1.2, 0.8])
    return w / w.sum()


if __name__ == "__main__":
    main()
